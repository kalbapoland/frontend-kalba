export function translateApiError(
  detail: unknown,
  t: (key: string) => string,
  fallback: string,
): string {
  if (typeof detail === "string" && API_ERROR_CODES.has(detail)) {
    return t(`api_errors.${detail}`);
  }
  return fallback;
}
